/** Measures every style and purpose, and writes the gain that hits its loudness tier to src/gains.ts. */

import { design, PEAK_LIMIT, PURPOSES, STYLES, TIER_LOUDNESS, tierOf } from "../src/design.ts";
import { Levels } from "../src/loudness.ts";

const rows = STYLES.map((style) => {
  const cells = PURPOSES.map((purpose) => {
    const { loudness, peak } = Levels.of(design(style, purpose));
    const correction = Math.min(TIER_LOUDNESS[tierOf(purpose)] - loudness, PEAK_LIMIT - peak);
    return `${purpose}: ${(10 ** (correction / 20)).toFixed(3)}`;
  });
  return `  ${style}: { ${cells.join(", ")} },`;
});

const file = `/** Generated by \`pnpm gains\`. Do not edit: change src/design.ts and regenerate. */

import type { Purpose, Style } from "./design.ts";

export const GAINS: Readonly<Record<Style, Readonly<Record<Purpose, number>>>> = {
${rows.join("\n")}
};
`;

await Bun.write(new URL("../src/gains.ts", import.meta.url), file);
console.log(`Wrote gains for ${STYLES.length * PURPOSES.length} sounds.`);
